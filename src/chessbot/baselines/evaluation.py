def material(board: chess.Board) -> int:
    """Material balance in centipawns from the side to move's point of view."""
    score = 0
    for piece in board.piece_map().values():
        value = PIECE_VALUES[piece.piece_type]
        score += value if piece.color == board.turn else -value
    return score


def evaluate(board: chess.Board) -> int:
    """Material + piece-square score from the side to move's point of view."""
    score = 0
    for square, piece in board.piece_map().items():
        # Table row 0 is rank 8: White indexes with a vertical flip, Black directly.
        index = square ^ 56 if piece.color == chess.WHITE else square
        value = PIECE_VALUES[piece.piece_type] + _PST[piece.piece_type][index]
        score += value if piece.color == board.turn else -value
    return score
